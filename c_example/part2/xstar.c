// 출력 결과(5x5 X 모양)
//*   *
// * *
//  *
// * *
//*   *

#include <stdio.h> // printf 같은 표준 입출력 함수를 쓰기 위한 헤더

int main(void) // 프로그램의 시작 지점
{
    // 5x5 격자를 위에서 아래로 한 줄씩(행) 그린다.
    for (int i = 1; i <= 5; ++i) { // i는 현재 행 번호(1~5)
        // 각 행에서 왼쪽에서 오른쪽으로 칸(열)을 채운다.
        for (int j = 1; j <= 5; ++j) { // j는 현재 열 번호(1~5)
            // 두 대각선 조건:
            // 1) i == j        : 왼쪽 위 → 오른쪽 아래 대각선
            // 2) i + j == 6    : 오른쪽 위 → 왼쪽 아래 대각선 (5x5라 합이 6)
            if (i + j == 6 || i == j) {
                printf("*"); // 대각선에 해당하면 별을 출력
            } else {
                printf(" "); // 그 외 위치는 공백을 출력
            }
        }

        // 한 행을 모두 출력했으면 줄을 바꿔 다음 행으로 이동
        printf("\n");
    }

    return 0; // 운영체제에 정상 종료를 알림
}
