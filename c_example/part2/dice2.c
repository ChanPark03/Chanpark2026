#include<stdio.h>       // 표준 입출력 라이브러리 (printf 사용)
#include<stdlib.h>      // rand(), srand() 함수 사용 (랜덤 숫자 생성)
#include <time.h>       // time() 함수 사용 (현재 시간 얻기)

int main(void){
    // 배열: 동일한 타입의 여러 값을 저장하는 자료구조
    // int 타입의 변수 30개를 연속된 메모리에 저장
    int dice[30];  // 크기 30인 int 배열 선언, 인덱스는 0~29까지 사용
    
    // 랜덤 시드 설정: 현재 시간을 기반으로 랜덤 숫자 생성
    // srand()를 호출하지 않으면 항상 같은 랜덤 값이 생성됨
    srand(time(NULL));  // time(NULL)은 현재 시간을 초 단위로 반환
    
    // 첫 번째 for 루프: 주사위 굴리기 (1~6 랜덤 값 저장)
    // 30번 반복하여 각 배열 요소에 랜덤한 주사위 값 저장
    for(int i = 0; i < 30; ++i){
        // [나눗셈] rand() % 6: 6으로 나누었을 때 나머지 값 (0~5)
        // [예시] 7 % 6 = 1, 8 % 6 = 2, 11 % 6 = 5
        // [핵심] n % 6은 항상 0~5 사이의 값이 됨
        // [용도] 특정 범위의 랜덤 숫자를 만들 때 사용
        // rand() % 6 + 1: 0~5에 +1하면 1~6 (주사위 값)
        dice[i] = rand() % 6 + 1;  // i번째 요소에 주사위 값(1~6) 저장
        
        printf("%d ,", dice[i]);    // 주사위 값 출력
        printf("%p ", &dice[i]);   // 배열 요소의 메모리 주소 출력 (&는 주소 연산자)
    }
    
    printf("\n");  // 줄바꿈
    
    // 두 번째 for 루프: 각 주사위 값에 10을 곱하기
    // 이미 저장된 배열의 각 요소 값을 수정
    for (int i = 0; i < 30; ++i){
        dice[i] *= 10;  // dice[i] = dice[i] * 10; 과 동일, 각 요소에 10 곱하기
        printf("%d ,", dice[i]);    // 10배 된 값 출력
        printf("%p ", &dice[i]);   // 메모리 주소는 동일함 (같은 위치의 값만 변경)
    }
    
    printf("\n");
    return 0;  // 프로그램 정상 종료
}

