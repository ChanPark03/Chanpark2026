// little endian, big endian
// 포인터 개념 요약:
// - 포인터는 "주소(메모리 위치)"를 저장하는 변수
// - &연산자: 변수의 주소를 얻음 (예: &a)
// - *연산자: 포인터가 가리키는 주소의 값을 읽거나 씀 (예: *p)
// - 포인터를 사용하면 함수에서 원본 값을 바꾸거나, 배열/문자열처럼 연속된 메모리를 다룰 수 있음

#include <stdio.h>

int main(void)
{
    int a = 0x12345678; // 포인터 대상이 될 변수
    char *p; // 포인터 선언: 주소를 담을 변수
    // 포인터(pointer): 다른 변수의 "주소"를 저장하는 변수
    // &a 는 a의 주소(메모리 위치)를 의미하고, p에 그 주소를 넣어준다
    // *p 는 p가 가리키는 주소에 저장된 "값"을 의미한다(역참조)
    // 여기서는 int 주소를 char*로 캐스팅하여 1바이트씩 읽는다
    p = (char*)&a; // & 사용: a의 주소를 얻어 p에 저장
    printf("*p : 0x%x\n", *(p)); // * 사용: p가 가리키는 값(첫 번째 바이트)을 읽음
    return 0; // 프로그램 정상 종료

// 해석:
// 메모리에서 정수 a가 어떤 순서로 저장되는지 확인하는 코드
// *(p + 0)은 첫 번째 바이트, *(p + 1)은 두 번째 바이트
// 리틀 엔디언이면 메모리 낮은 주소에 0x78부터 저장됨
// 빅 엔디언이면 메모리 낮은 주소에 0x12부터 저장됨
// 따라서 *(p + 0)이 0x78이면 리틀 엔디언, 0x12이면 빅 엔디언
}
