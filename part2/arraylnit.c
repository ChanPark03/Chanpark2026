#include <stdio.h>      // 표준 입출력 라이브러리 (printf 함수 사용을 위해 포함)

int main(void){
    // 배열 초기화 방법 1: 크기를 명시하고 중괄호로 값 목록 초기화
    // 크기 5인 int 배열을 선언하고 1, 2, 3, 4, 5로 초기화
    int nums[5] = {1, 2, 3, 4, 5};  // nums[0]=1, nums[1]=2, ..., nums[4]=5
    
    // 배열 초기화 방법 2: 크기를 생략하고 값 목록만 지정
    // 중괄호 안에 값의 개수에 따라 배열 크기가 자동으로 5로 결정됨
    int nums2[] = {1, 2, 3, 4, 5};  // 자동으로 크기 5로 설정됨
    
    // 배열 초기화 방법 3: 선언한 크기보다 초기값 개수가 적은 경우
    // 크기는 10이지만 초기값은 5개만 제공, 나머지 5개는 자동으로 0으로 초기화됨
    int nums3[10] = {1, 2, 3, 4, 5};  // nums3[0~4]=1~5, nums3[5~9]=0
    
    // 배열 초기화 방법 4: 크기만 선언하고 초기화하지 않음
    // 메모리에는 쓰레기값(garbage value)이 들어감, 초기화되지 않은 변수는 사용 금지
    int nums4[50];  // 값이 쓰레기, 사용 전 반드시 초기화 필요
    
    // 배열 초기화 방법 5: 모든 요소를 0으로 초기화
    // 중괄호 안에 0을 하나만 쓰면 모든 요소가 0으로 초기화됨
    int nums5[50] = {0};  // nums5[0~49] 모두 0으로 초기화
    
    // 배열의 크기를 동적으로 구하는 방법
    // sizeof(배열명): 배열 전체 바이트 크기 (50 * 4 = 200바이트)
    // sizeof(int): int 타입 하나의 크기 (4바이트)
    // 전체 크기를 int 크기로 나누면 배열 요소 개수(50)를 얻을 수 있음
    int n = sizeof(nums5) / sizeof(int);  // n = 50
    
    // for 루프를 사용하여 배열의 모든 요소에 접근
    // i는 0부터 시작, n(50)보다 작을 때까지 반복
    // ++i는 선행 증가 연산자로 i를 1 증가시킨 후 조건 검사
    for (int i = 0; i < n; ++i){
        printf("%d", nums5[i]);  // nums5[i]의 값을 출력, i는 0~49까지 변경
    }
    
    // main 함수가 정상적으로 종료되었음을 나타내는 반환값
    return 0; 
}

